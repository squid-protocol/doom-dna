"""DOOM-E12 analysis: scores predictions P1a..P7 exactly as registered (preregistration/E12_METHOD_LADDER.md §D) and writes results/e12/E12_RESULTS.md.
Usage: python e12_analyze.py [table.csv]   (default results/e12/e12_table.csv)"""
import sys, numpy as np, pandas as pd
from pathlib import Path
from scipy.stats import kendalltau
R = Path(__file__).resolve().parents[1] / "results" / "e12"
src = Path(sys.argv[1]) if len(sys.argv) > 1 else R / "e12_table.csv"
d = pd.read_csv(src, dtype={"N": str}); d["N"] = d["N"].astype(str)
REG = "|0.01|0.8"; F0, F1C = "F0" + REG, "F1c" + REG
SL = sorted(d[d.group == "SL"].program.unique()); TR = sorted(d[d.group == "T"].program.unique())
HARD = ["lua", "nginx", "room4doom", "rust-doom"]; HELD = ["leveldb", "curl", "libuv"]
def cell(prog, rung, N, truth, col):
    x = d[(d.program == prog) & (d.rung == rung) & (d.N == str(N)) & (d.truth == truth)]
    return float(x[col].iloc[0]) if len(x) and pd.notna(x[col].iloc[0]) else np.nan
def full_or(prog, rung, N, truth, col):  # N if list is at least N long, else the full list
    e = cell(prog, rung, "full", truth, "emitted"); return cell(prog, rung, "full" if (np.isnan(e) or e < N) else N, truth, col)
out = []; P = out.append
def verdict(name, text, ok, detail):
    st = "INCOMPLETE (missing inputs)" if "nan" in detail.lower().replace("nance", "") else ("PASSED" if ok else "FAILED")
    P(f"### {name}: {st}\n{text}\n\n{detail}\n")
P("# DOOM-E12 results: method ladder\n\nGenerated by `measure/e12_analyze.py` from `results/e12/e12_table.csv`. Design and predictions: `preregistration/E12_METHOD_LADDER.md` (registered 4a5b9b1 before any scoring). `chocolate-doom` (development port) is excluded from every count.\n")
nSL = len(SL); P(f"Scored programs: {nSL} same-language, {len(TR)} translations.\n")
# P1a
v = {p: cell(p, F0, "full", "j09", "precision") for p in SL}; n = sum(x >= 0.90 for x in v.values() if not np.isnan(x))
verdict("P1a", f"F0 at the registered setting has precision >= 0.90 (Jaccard 0.9 truth) on >= 15 of {nSL}.", n >= 15, f"{n} of {nSL}. Median precision {np.nanmedian(list(v.values())):.3f}; range {np.nanmin(list(v.values())):.3f} to {np.nanmax(list(v.values())):.3f}.")
# P1b
rows = []
for p in SL:
    rf, rE = full_or(p, F0, 250, "j09", "recall"), cell(p, "E3c", 250, "j09", "recall"); pr = cell(p, "E3c", 250, "j09", "precision")
    rows.append((p, rf, rE, rE - rf, pr))
t = pd.DataFrame(rows, columns=["program", "F0_recall", "E3c_recall", "gain", "E3c_precision"]); ok = ((t.gain >= 0.05) & (t.E3c_precision >= 0.75)).sum()
verdict("P1b", f"At N=250 (F0 at min(250, its full list)), E3c recall exceeds F0's by >= 0.05 with E3c precision >= 0.75, on >= 10 of {nSL}.", ok >= 10, f"{ok} of {nSL}. Median gain {t.gain.median():+.3f}; median E3c precision {t.E3c_precision.median():.3f}.\n\n" + t.round(3).to_markdown(index=False))
# P2
em = {}
for p in ["gore", "doom-scheme", "dartdoom"]:
    el = cell(p, F0, "full", "name", "eligible"); em[p] = (cell(p, F0, "full", "name", "emitted") / el, cell(p, F1C, "full", "name", "emitted") / el)
prec_g = cell("gore", "E3c", 250, "name", "precision"); ok = all(a < 0.05 and b < 0.05 for a, b in em.values()) and prec_g >= 0.5
verdict("P2", "On gore, doom-scheme, dartdoom: F0 and F1c each emit < 5% of eligible functions; E3c name-key precision >= 0.50 at N=250 on gore.", ok, "Share emitted (F0, F1c): " + "; ".join(f"{k} {a:.3%}, {b:.3%}" for k, (a, b) in em.items()) + f". gore E3c precision at 250: {prec_g:.3f}.")
# P3
rows = [(p, cell(p, "G1", 100, "j09", "precision"), cell(p, "G2", 100, "j09", "precision")) for p in SL]; t = pd.DataFrame(rows, columns=["program", "G1", "G2"]); t["gap"] = t.G2 - t.G1; ok = (t.gap >= 0.30).sum()
verdict("P3", f"At N=100, G1 (call graph only) precision is >= 0.30 below G2 on >= 14 of {nSL}.", ok >= 14, f"{ok} of {nSL}. Median gap {t.gap.median():+.3f}.\n\n" + t.round(3).to_markdown(index=False))
# P4 (translations: no function-level recall exists; uses true pairs / eligible)
rows = []
for p in TR:
    el = cell(p, "E3", 250, "name", "eligible"); rows.append((p, cell(p, "E3c", 250, "name", "true") / el, cell(p, "E3", 250, "name", "true") / el))
t = pd.DataFrame(rows, columns=["program", "E3c", "E3"]); t["gain"] = t.E3c - t.E3; ok = (t.gain < 0.05).sum()
verdict("P4", f"Calibration adds < 0.05 (true name-key pairs / eligible functions, since translations have no function-level recall) at N=250 on >= 5 of {len(TR)} translations.", ok >= 5, f"{ok} of {len(TR)}.\n\n" + t.round(3).to_markdown(index=False))
# P5
rows = [(p, cell(p, "E1", 250, "j09", "precision"), cell(p, "E3", 250, "j09", "precision")) for p in SL]; t = pd.DataFrame(rows, columns=["program", "E1", "E3"]); t["drop"] = t.E1 - t.E3; ok = (t["drop"] <= 0.15).sum()
verdict("P5", f"From E1 to E3 at N=250, precision falls by <= 0.15 on >= 14 of {nSL}.", ok >= 14, f"{ok} of {nSL}. Median change {-t['drop'].median():+.3f}.\n\n" + t.round(3).to_markdown(index=False))
# P6
ext = ["S", "E1", "E2", "E3", "E3c"]; rows = []
for p in HARD:
    rows.append([p] + [cell(p, r, 100, "all_false", "emitted") for r in ext])
t = pd.DataFrame(rows, columns=["control"] + ext); half1 = bool((t[ext] >= 90).all().all())
g = d[d.rung == "GATE"].set_index("program"); rej = [p for p in HARD[:2] + HELD if p in g.index and not bool(g.loc[p, "passes"])]; need = HARD[:2] + HELD
acc = sum(bool(g.loc[p, "passes"]) for p in SL if p in g.index); half2 = (len(rej) == len(need)) and acc >= 17
verdict("P6", "At N=100 the extension rungs (S, E1 to E3c) emit >= 90 pairs on every hard-negative and scratch-rewrite control, and the gate rejects lua, nginx, leveldb, curl, libuv and accepts >= 17 of 19 SL.", half1 and half2,
        f"Emission half: {'passed' if half1 else 'failed'}. Gate half: rejected {len(rej)} of {len(need)} ({', '.join(rej)}); accepted {acc} of {nSL} SL.\n\nPairs emitted at N=100:\n\n" + t.to_markdown(index=False))
# P7
rungs = ["G0", "G1", "G2", "S", "E1", "E2", "E3", "E3c", F0, "F1a" + REG, "F1b" + REG, F1C]
def mean_rec(tag): return [np.nanmean([full_or(p, r, 250, tag, "recall") for p in SL]) for r in rungs]
a, b = mean_rec("j09"), mean_rec("j06"); tau = kendalltau(a, b)[0]
verdict("P7", "Kendall tau >= 0.8 between the rung orderings (mean recall at N=250) under the Jaccard 0.9 and 0.6 truths.", tau >= 0.8, f"tau = {tau:.3f}.\n\n" + pd.DataFrame({"rung": rungs, "recall_j09": a, "recall_j06": b}).round(3).to_markdown(index=False))
# Matched-volume tables
P("## Matched-volume table (mean over SL programs, Jaccard 0.9 truth)\n")
rows = []
for r in ["G0", "G1", "G2", "S", "E1", "E2", "E3", "E3c", F0, F1C]:
    rows.append([r] + [f"{np.nanmean([cell(p, r, N, 'j09', 'precision') for p in SL]):.3f} / {np.nanmean([cell(p, r, N, 'j09', 'recall') for p in SL]):.3f}" for N in (50, 100, 250, 500, "full")])
P("Cell = precision / function-level recall.\n\n" + pd.DataFrame(rows, columns=["rung", "N=50", "N=100", "N=250", "N=500", "full"]).to_markdown(index=False) + "\n")
# Development port, translations, controls
dv = d[d.group == "DEV"]
if len(dv): P("## Development port (chocolate-doom; not counted)\n\n" + dv[(dv.N == "250") & (dv.truth == "j09")][["rung", "emitted", "precision", "recall"]].round(3).to_markdown(index=False) + "\n")
P("## Translations (name key; lower bound, never mixed with text truth)\n")
tt = d[(d.group == "T") & (d.N == "250") & (d.truth == "name") & d.rung.isin(["G1", "G2", "S", "E1", "E3", "E3c", F0, F1C])]
P(tt.pivot(index="program", columns="rung", values="precision").round(3).to_markdown() + "\n")
P("## Controls: emitted pairs and false pairs per 1,000 eligible functions at N=100\n")
cc = d[(d.group.isin(["K", "H"])) & (d.N == "100") & (d.truth == "all_false") & d.rung.isin(ext + ["G1", "G2"])]
P(cc.pivot(index="program", columns="rung", values="emitted").to_markdown() + "\n")
# Rewiring null
rw = d[d.rung.str.startswith("REWIRED")]
if len(rw):
    P("## Rewiring null (degree-preserving; precision at N=250, mean over draws and SL programs, Jaccard 0.9)\n")
    rows = []
    for r in ["G2", "S", "E3", "E3c"]:
        x = rw[(rw.rung == "REWIRED|" + r) & (rw.N == "250") & (rw.truth == "j09") & rw.program.isin(SL)]
        rows.append((r, np.nanmean([cell(p, r, 250, "j09", "precision") for p in SL]), x.precision.mean()))
    P(pd.DataFrame(rows, columns=["rung", "real graph", "rewired graph"]).round(3).to_markdown(index=False) + "\n")
P("## Not done here\nThe blind audit of 40 pairs per translation (model raters) is a separate step; no multiplicity correction is claimed.\n")
(R / "E12_RESULTS.md").write_text("\n".join(out)); print("wrote", R / "E12_RESULTS.md")

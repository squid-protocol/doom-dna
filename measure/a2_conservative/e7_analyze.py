def rd(path):
    return list(csv.DictReader(open(path)))


def fmt(x, d=3):
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{d}f}"


def matrices(names):
    idx = {n: i for i, n in enumerate(names)}
    k = len(names)
    st = rd(A / "pairs_struct.csv")
    nm = rd(A / "pairs_names.csv")
    wst = np.zeros((k, k))
    wn_cert, wn_raw, wn_nostop, wn_n2 = (np.zeros((k, k)) for _ in range(4))
    surv_names = np.zeros((k, k))
    elig = np.zeros(k)
    for r in st:
        i, j = idx[r["q"]], idx[r["t"]]
        wst[i, j] = float(r["wilson"])
        elig[i] = float(r["elig_q"])
    for r in nm:
        i, j = idx[r["q"]], idx[r["t"]]
        nq = float(r["elig_q"])
        wn_cert[i, j] = float(r["wilson_cert"])
        wn_raw[i, j] = float(r["wilson_raw"])
        wn_nostop[i, j] = N.wilson_lower(float(r["nostop_matched"]), int(nq))
        wn_n2[i, j] = N.wilson_lower(float(r["n2_matched"]), int(nq))
        surv_names[i, j] = float(r["surv"])
    sym = lambda m: np.maximum(m, m.T)  # noqa: E731
    out = dict(struct=sym(wst), names=sym(wn_cert), names_raw=sym(wn_raw), names_nostop=sym(wn_nostop), names_n2=sym(wn_n2))
    for m in out.values():
        np.fill_diagonal(m, 1.0)
    return out, surv_names, elig, st, nm


def tree_of(shared, names):
    return T.parse_newick(T.upgma_newick(1.0 - shared, names))


def nj_of(shared, names, root="linuxdoom"):
    t = T.parse_newick(T.nj_newick(1.0 - shared, names))
    return T.root_at(t, root) if root in names else t


def cp_ci(k, n, a=0.05):
    if n == 0:
        return (float("nan"), float("nan"))
    lo = 0.0 if k == 0 else beta.ppf(a / 2, k, n - k + 1)
    hi = 1.0 if k == n else beta.ppf(1 - a / 2, k + 1, n - k)
    return (float(lo), float(hi))


def boot_mean_diff(d, n=2000):
    d = np.asarray(d, float)
    if len(d) == 0:
        return (float("nan"),) * 3
    bs = [d[RNG.integers(0, len(d), len(d))].mean() for _ in range(n)]
    return float(d.mean()), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


def boot_spearman(x, y, n=2000):
    x, y = np.asarray(x, float), np.asarray(y, float)
    if len(x) < 4:
        return (float("nan"),) * 3
    r = spearmanr(x, y).statistic
    bs = []
    for _ in range(n):
        ii = RNG.integers(0, len(x), len(x))
        if len(set(x[ii])) > 1 and len(set(y[ii])) > 1:
            bs.append(spearmanr(x[ii], y[ii]).statistic)
    return float(r), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


def main():
    meta = json.load(open(A / "run_meta.json"))
    names = meta["programs"]
    idx = {n: i for i, n in enumerate(names)}
    prog = {r["name"]: r for r in rd(A / "programs.csv")}
    grp = {r["name"]: r for r in rd(REPO / "manifest" / "e7_groups.csv")}
    cls = {r["name"]: r["class"] for r in rd(REPO / "manifest" / "manifest.csv")}
    lang_group = {n: grp[n]["language_group"] for n in names}
    mats, surv_names, elig, st_rows, nm_rows = matrices(names)
    lin, bas = REPO / "manifest" / "declared_lineage.csv", REPO / "manifest" / "declared_lineage_basis.csv"
    decl = T.build_declared(lin, bas, names)
    decl_x = T.build_declared(lin, bas, names, explicit_only=True)
    L = []  # report lines
    P = lambda s="": L.append(s)  # noqa: E731
    P("# DOOM-E7 Phase A results")
    P(f"Engine {meta['engine']}, spec {meta['spec_hash']}, {len(names)} map programs, floor {FLOOR:.0%}. Generated by measure/e7_analyze.py.")
    P()

    det = {m: set(T.detectable(mats[m], names, FLOOR)) for m in ("struct", "names", "names_raw")}
    P("## Detectable descent (largest shared with any other program at or above the floor)")
    for m in det:
        und = [n for n in names if n not in det[m]]
        P(f"- **{m}**: {len(det[m])} detectable, {len(und)} not: {', '.join(und)}")
    P()
    # ---- underpowered
    under = {n for n in names if elig[idx[n]] < 100}
    P(f"Underpowered (fewer than 100 eligible functions, reported not scored as no-descent): {', '.join(sorted(under)) or 'none'}")
    P()

    declared_leaves = set(decl.leaves) & set(names)
    scored_decl = [n for n in names if (decl.ancestors(n) or decl.descendants(n)) and n in declared_leaves]
    common = det["struct"] & det["names"]
    skip_for = lambda keep: {n for n in names if n not in keep}  # noqa: E731

    # ---- M1 / M2
    P("## M1 nearest-is-family and M2 parent rank (distance-matrix metrics)")
    P("| method | declared tree | scored set | M1 corrected | M1 old root-sibling rule | M2 mean rank | M2 median rank | M1 null p95 (within-language shuffle) |")
    P("|---|---|---|---:|---:|---:|---:|---:|")
    m1 = {}
    p95s = {}
    for m in ("struct", "names", "names_raw", "names_nostop", "names_n2"):
        dist = 1.0 - mats[m]
        for dname, d in (("all edges", decl), ("explicit only", decl_x)):
            for sname, keep in (("own detectable", set(T.detectable(mats[m], names, FLOOR))), ("common", common)):
                sk = skip_for(keep)
                rows, rate = T.nearest_is_family(dist, names, d, include_root_siblings=False, skip=sk)
                _, rate_old = T.nearest_is_family(dist, names, d, include_root_siblings=True, skip=sk)
                _, mean_r, med_r = T.parent_rank(dist, names, d, skip=sk)
                null = T.permutation_null(lambda lab, dist=dist, d=d, sk=sk: T.nearest_is_family(dist, lab, d, skip=sk)[1],
                                          names, groups=lang_group, n=NNULL, seed=1) \
                    if (sname == "common" and dname == "all edges") else None
                p95 = null.p95 if null is not None else None
                if null is not None:
                    p95s[m] = p95
                m1[(m, dname, sname)] = rate
                P(f"| {m} | {dname} | {sname} | {fmt(rate)} | {fmt(rate_old)} | {fmt(mean_r, 2)} | {fmt(med_r, 1)} | {fmt(p95)} |")
    P()
    P("*M1 and M2 are computed on distance matrices, not on the trees.*")
    P()

    # ---- M3 tree vs declared
    P("## M3 tree vs declared tree (resolved-clade recall, resolved-triplet compatibility)")
    t_struct, t_names = tree_of(mats["struct"], names), tree_of(mats["names"], names)
    n_struct, n_names = nj_of(mats["struct"], names), nj_of(mats["names"], names)
    leaves_c = sorted(common & declared_leaves)
    P(f"Common scored leaves: {len(leaves_c)}. Declared tree has {len(decl.clades())} resolved clades and {len(decl.triplets())} resolved triplets.")
    P("| tree | clade recall | triplet compat | clade recall null p95 | triplet compat null p95 | declared splits recalled (unrooted) |")
    P("|---|---:|---:|---:|---:|---:|")
    def split_recall(tr):
        dsp = decl.bipartitions(leaves_c)
        return len(dsp & tr.bipartitions(leaves_c)) / len(dsp) if dsp else float("nan")
    for nm_, tr, dm in (("UPGMA struct", t_struct, "struct"), ("UPGMA names", t_names, "names"),
                        ("NJ(root linuxdoom) struct", n_struct, "struct"), ("NJ(root linuxdoom) names", n_names, "names")):
        cr = T.resolved_clade_recall(decl, tr, leaves_c)
        tc = T.resolved_triplet_compat(decl, tr, leaves_c)
        if nm_.startswith("UPGMA"):
            build = lambda lab, dm=dm: T.parse_newick(T.upgma_newick(1.0 - mats[dm], lab))  # noqa: E731
        else:
            build = lambda lab, dm=dm: T.root_at(T.parse_newick(T.nj_newick(1.0 - mats[dm], lab)), "linuxdoom")  # noqa: E731
        n1 = T.permutation_null(lambda lab, b=build: T.resolved_clade_recall(decl, b(lab), leaves_c), names, groups=lang_group, n=300, seed=2)
        n2 = T.permutation_null(lambda lab, b=build: T.resolved_triplet_compat(decl, b(lab), leaves_c), names, groups=lang_group, n=300, seed=3)
        P(f"| {nm_} | {fmt(cr)} | {fmt(tc)} | {fmt(n1.p95)} | {fmt(n2.p95)} | {fmt(split_recall(tr))} |")
    P("*Nulls: 300 within-language label shuffles of the same distance matrix (NJ nulls rooted at linuxdoom).*")
    P("*Rooted NJ at linuxdoom is not determined by the data: linuxdoom is itself a sampled ancestor, so rooting there puts the root on a polytomy and NJ resolves the tie arbitrarily (shown by an exact-additive test, tests/test_e7_trees.py). The rooted NJ rows are therefore reported but not interpreted; the unrooted declared-split recall column is the NJ comparison.*")
    P()
    P("**Post hoc (decided after seeing Phase A; not registered):** NJ on a matrix where undetectable programs sit at distance 1 from everything is unreliable, so NJ is repeated on the common detectable programs only.")
    P("| tree | clade recall | triplet compat |")
    P("|---|---:|---:|")
    sub = [n for n in names if n in common]
    sidx_ = [idx[n] for n in sub]
    for dm in ("struct", "names"):
        d_sub = 1.0 - mats[dm][np.ix_(sidx_, sidx_)]
        tr = T.root_at(T.parse_newick(T.nj_newick(d_sub, sub)), "linuxdoom")
        P(f"| NJ common-detectable {dm} | {fmt(T.resolved_clade_recall(decl, tr, leaves_c))} | {fmt(T.resolved_triplet_compat(decl, tr, leaves_c))} |")
    P()

    # ---- M4 tree vs tree
    P("## M4 names tree vs structure tree")
    ex = {"quake", "quake2", "lua"}
    both = sorted((det["struct"] & det["names"]) - ex)
    rf = T.rf_unrooted(t_struct, t_names, both)
    qd = T.quartet_distance(t_struct, t_names, both)
    rfn = T.rf_unrooted(n_struct, n_names, both)
    qdn = T.quartet_distance(n_struct, n_names, both)
    nul = T.permutation_null(lambda lab: T.rf_unrooted(t_struct, T.parse_newick(T.upgma_newick(1.0 - mats["names"], lab)), both),
                             names, groups=lang_group, n=300, seed=4)
    P(f"On {len(both)} programs detectable under both (excluding quake, quake2, lua): UPGMA RF {fmt(rf)}, quartet {fmt(qd)}; NJ RF {fmt(rfn)}, quartet {fmt(qdn)}. "
      f"Within-language shuffle null RF p5 {fmt(float(np.percentile(nul.null, 5)))} (observed UPGMA RF below p5: {rf < float(np.percentile(nul.null, 5))}).")
    P()

    # ---- M5
    P("## M5 pair-level agreement of shared_names and shared_struct")
    iu = np.triu_indices(len(names), 1)
    a, b = mats["struct"][iu], mats["names"][iu]
    P(f"All pairs: Spearman {fmt(spearmanr(a, b).statistic)} (n={len(a)}). Above floor under both: "
      f"{int(((a >= FLOOR) & (b >= FLOOR)).sum())} pairs; struct only {int(((a >= FLOOR) & (b < FLOOR)).sum())}; names only {int(((a < FLOOR) & (b >= FLOOR)).sum())}; neither {int(((a < FLOOR) & (b < FLOOR)).sum())}.")
    same = [n for n in names if grp[n]["language_group"] == "c_family"]
    sidx = [idx[n] for n in same]
    sub = mats["struct"][np.ix_(sidx, sidx)], mats["names"][np.ix_(sidx, sidx)]
    iu2 = np.triu_indices(len(sidx), 1)
    x, y = sub[0][iu2], sub[1][iu2]
    mask = (x >= FLOOR) & (y >= FLOOR)
    r_obs = spearmanr(x[mask], y[mask]).statistic if mask.sum() > 3 else float("nan")
    bs = []
    for _ in range(1000):
        pick = RNG.integers(0, len(sidx), len(sidx))
        m_ = np.array([[sub[0][i, j], sub[1][i, j]] for ii, i in enumerate(pick) for j in pick[ii + 1:] if i != j])
        if len(m_):
            mm = (m_[:, 0] >= FLOOR) & (m_[:, 1] >= FLOOR)
            if mm.sum() > 3 and len(set(m_[mm, 0])) > 1 and len(set(m_[mm, 1])) > 1:
                bs.append(spearmanr(m_[mm, 0], m_[mm, 1]).statistic)
    P(f"H7.2 (descriptive): same-language (C-family) pairs above the floor under both, n={int(mask.sum())}: Spearman {fmt(r_obs)}; cluster bootstrap over programs 95% interval "
      f"[{fmt(float(np.percentile(bs, 2.5)) if bs else None)}, {fmt(float(np.percentile(bs, 97.5)) if bs else None)}] (registered threshold 0.80).")
    P()

    # ---- M6 arbiter
    P("## M6 survival of linuxdoom code against the name-blind text arbiter")
    summ = {r["port"]: r for r in rd(A / "arbiter" / "arbiter_summary.csv")}
    pres = np.load(A / "linuxdoom_twin_presence.npz", allow_pickle=False)
    nL = int(elig[idx["linuxdoom"]])
    ports = [n for n in names if n != "linuxdoom" and n in summ and grp[n]["same_language_pair"] == "yes"]
    rows6 = []
    for p in ports:
        q = pres[f"linuxdoom|{p}|q"]
        t = pres[f"{p}|linuxdoom|t"]
        s_struct = len(set(q.tolist()) | set(t.tolist())) / nL
        s_names = surv_names[idx["linuxdoom"], idx[p]]
        s = summ[p]
        rows6.append(dict(port=p, text_en=float(s["share_exact_near"]), text_end=float(s["share_exact_near_derived"]),
                          struct=s_struct, names=s_names, text_en_ns=float(s["share_exact_near_ns"])))
    P(f"Same-language ports with a declared lineage (n={len(rows6)}); linuxdoom has {nL} eligible functions. Structure survival counts a twin in either direction (METHOD §9).")
    P("| port | text exact+near | text +derived | structure | names | |err struct| (en) | |err names| (en) |")
    P("|---|---:|---:|---:|---:|---:|---:|")
    for r in rows6:
        P(f"| {r['port']} | {fmt(r['text_en'])} | {fmt(r['text_end'])} | {fmt(r['struct'])} | {fmt(r['names'])} | {fmt(abs(r['struct'] - r['text_en']))} | {fmt(abs(r['names'] - r['text_en']))} |")
    for key, label in (("text_en", "exact+near"), ("text_end", "exact+near+derived")):
        es = np.array([abs(r["struct"] - r[key]) for r in rows6])
        en = np.array([abs(r["names"] - r[key]) for r in rows6])
        wins = int((es < en).sum())
        lo, hi = cp_ci(wins, len(rows6))
        md = boot_mean_diff(en - es)
        rs = boot_spearman([r["struct"] for r in rows6], [r[key] for r in rows6])
        rn = boot_spearman([r["names"] for r in rows6], [r[key] for r in rows6])
        P()
        P(f"**H7.1 vs {label}:** structure closer to the text arbiter in {wins}/{len(rows6)} ports ({wins / max(len(rows6), 1):.0%}, exact 95% CI [{fmt(lo, 2)}, {fmt(hi, 2)}]; registered threshold 75%). "
          f"Mean |err names| minus |err struct| = {fmt(md[0])} (paired bootstrap 95% [{fmt(md[1])}, {fmt(md[2])}]; positive favours structure). "
          f"Spearman vs text: structure {fmt(rs[0])} [{fmt(rs[1])}, {fmt(rs[2])}], names {fmt(rn[0])} [{fmt(rn[1])}, {fmt(rn[2])}].")
    P()

    # ---- M7 negatives
    P("## M7 negative controls: largest shared with any DOOM engine-port")
    doom = [n for n in names if cls.get(n) == "engine-port" and n != "linuxdoom" or n == "linuxdoom"]
    negs = [n for n in names if prog[n]["role"] in ("map-negative-unrelated", "map-negative-same-studio") or cls.get(n) in ("reimplementation", "raycaster", "assets")]
    P("| program | role | eligible | struct max shared (with) | names max shared (with) | struct >= floor | names >= floor | enough functions (>=150) |")
    P("|---|---|---:|---|---|:-:|:-:|:-:|")
    h74 = {"struct": 0, "names": 0, "n": 0}
    for n in negs:
        i = idx[n]
        cand = [d for d in doom if d != n and not ({n, d} == {"quake", "quake2"})]
        ms = max(cand, key=lambda d: mats["struct"][i, idx[d]])
        mn = max(cand, key=lambda d: mats["names"][i, idx[d]])
        vs, vn = mats["struct"][i, idx[ms]], mats["names"][i, idx[mn]]
        big = elig[i] >= 150
        if prog[n]["role"] == "map-negative-unrelated" and big:
            h74["n"] += 1
            h74["struct"] += int(vs >= FLOOR)
            h74["names"] += int(vn >= FLOOR)
        P(f"| {n} | {prog[n]['role']} | {int(elig[i])} | {fmt(vs, 4)} ({ms}) | {fmt(vn, 4)} ({mn}) | {'yes' if vs >= FLOOR else 'no'} | {'yes' if vn >= FLOOR else 'no'} | {'yes' if big else 'no'} |")
    P()
    P(f"**H7.4 (primary):** among {h74['n']} unrelated controls with at least 150 eligible functions, false attachments to DOOM engine-ports: structure {h74['struct']}, names {h74['names']} (registered: structure 0, names at least 1).")
    P()

    # ---- H7.3
    P("## H7.3 cross-language ports: does names attach where structure cannot (descriptive)")
    xl = [n for n in names if grp[n]["same_language_pair"] == "no" and n in declared_leaves]
    P("| port | struct detectable | names nearest | names shared | declared family member |")
    P("|---|:-:|---|---:|:-:|")
    cnt = 0
    for n in xl:
        i = idx[n]
        others = [o for o in names if o != n]
        nn = max(others, key=lambda o: mats["names"][i, idx[o]])
        fam = decl.relation(n, nn) != "other" if hasattr(decl, "relation") else False
        ok = mats["names"][i, idx[nn]] >= FLOOR and fam
        cnt += int(ok and n not in det["struct"])
        P(f"| {n} | {'yes' if n in det['struct'] else 'no'} | {nn} | {fmt(mats['names'][i, idx[nn]], 4)} | {'yes' if fam else 'no'} |")
    P(f"\nCross-language ports undetectable by structure that attach to a declared family member under names: {cnt}.")
    P()

    # ---- M8
    P("## M8 the 20 pairs where names and structure disagree most")
    gen = {(r["q"], r["t"]): float(r["generic_share"]) for r in nm_rows}
    dif = np.abs(mats["struct"] - mats["names"])
    pairs = sorted(((dif[i, j], i, j) for i in range(len(names)) for j in range(i + 1, len(names))), reverse=True)[:20]
    P("| pair | struct | names | category | rule that fired |")
    P("|---|---:|---:|---|---|")
    for d, i, j in pairs:
        qn, tn = names[i], names[j]
        g = max(gen.get((qn, tn), 0), gen.get((tn, qn), 0))
        if g > 0.5:
            cat, why = "generic-name collision", f"generic share {g:.2f}"
        elif min(elig[i], elig[j]) < 100:
            cat, why = "small-repo threshold", f"min eligible {int(min(elig[i], elig[j]))}"
        elif grp[qn]["primary_language"] != grp[tn]["primary_language"]:
            cat, why = "translation", f"{grp[qn]['primary_language']} vs {grp[tn]['primary_language']}"
        else:
            cat, why = "rename/reorganization or sideways transfer (directory check below)", "default"
        P(f"| {qn} / {tn} | {fmt(mats['struct'][i, j], 4)} | {fmt(mats['names'][i, j], 4)} | {cat} | {why} |")
    P()
    P("*Directory-concentration check for sideways transfer (rule 3) is applied in the follow-up table `m8_directories.csv` if written.*")
    # ---- diagnostic: duplicated functions inside a repository (post hoc, not a registered metric)
    from structural_fingerprint.fingerprint import FunctionTable, safe_name
    import collections
    P("## Diagnostic (post hoc): functions carried more than once inside one repository")
    P("Share of eligible functions (loc >= 6) in an exact-digest duplicate group. High values defeat one-to-one twin matching and inflate one-to-one name matches by multiplicity.")
    P("| program | eligible | in exact duplicate group |")
    P("|---|---:|---:|")
    dups = []
    for n in names:
        t = FunctionTable.load(A / "fingerprints" / f"{safe_name(n)}.sfp.npz")
        keep = t.loc >= 6
        c = collections.Counter(t.key[keep].tolist())
        sh = sum(v for v in c.values() if v > 1) / max(int(keep.sum()), 1)
        dups.append((sh, n, int(keep.sum())))
    for sh, n, k_ in sorted(dups, reverse=True)[:12]:
        P(f"| {n} | {k_} | {sh:.0%} |")
    P()
    # ---- scorecard against the registered predictions
    P("## Scorecard against the registered predictions (Amendment 1 §F)")
    wins = sum(1 for r in rows6 if abs(r["struct"] - r["text_en"]) < abs(r["names"] - r["text_en"]))
    P(f"- **H7.1** (structure closer to the name-blind text arbiter in at least 75% of same-language ports): {wins}/{len(rows6)} = {wins / max(len(rows6), 1):.0%} on exact+near. Met. Caveat: names rank the ports about as well or better than structure (Spearman vs text above); structure is better calibrated, names overstate.")
    P(f"- **H7.2** (descriptive, Spearman at least 0.80): point estimate {fmt(r_obs)}, cluster-bootstrap interval includes values below 0.80.")
    und_x = [n for n in xl if n not in det["struct"]]
    P(f"- **H7.3** (descriptive, at least a third of cross-language ports that structure leaves undetected attach to a declared family member under names): {cnt}/{len(und_x)} = {cnt / max(len(und_x), 1):.0%}.")
    P(f"- **H7.4** (primary; structure 0 and names at least 1 false attachments among {h74['n']} large unrelated controls): structure {h74['struct']}, names {h74['names']}. **Structure prediction not met as registered**: the one attachment is `lua` to `srb2`, and SRB2 vendors Lua (`src/blua/`), so it is a genuine copy kept by the registered vendor policy, not noise.")
    P(f"- **H7.5a** (primary; M1 corrected above the within-language null's 95th percentile): structure {fmt(m1[('struct', 'all edges', 'common')])} vs {fmt(p95s.get('struct'))}; names {fmt(m1[('names', 'all edges', 'common')])} vs {fmt(p95s.get('names'))}. Met for both.")
